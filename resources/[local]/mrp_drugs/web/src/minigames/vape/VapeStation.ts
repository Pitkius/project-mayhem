import type { PixiStage } from '@/engine/pixi/stage';
import type { StationPayload } from '@/types/protocol';
import type { StationCallbacks, StationController } from '../types';
import { createStationRuntime, runSequence } from '../shared/createRuntime';
import { vapeStages } from './scenes';

export function runVapeStation(
  stage: PixiStage,
  payload: StationPayload,
  cb: StationCallbacks,
): StationController {
  const { rt, controller } = createStationRuntime(stage, 'vape', cb);
  void runSequence(rt, vapeStages(rt, payload.mode, payload.quantity ?? 1));
  return controller();
}
